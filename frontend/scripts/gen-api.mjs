import fs from 'node:fs'
import path from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'

const url = process.env.OPENAPI_URL ?? 'http://localhost:8080/api-docs'

const ast = await openapiTS(new URL(url))
const contents = astToString(ast)

const outDir = path.resolve('src/api')
fs.mkdirSync(outDir, { recursive: true })
const outFile = path.join(outDir, 'schema.d.ts')
fs.writeFileSync(
  outFile,
  `/**\n * Generated by \`npm run gen:api\` from ${url}\n * Do not edit manually.\n */\n${contents}`,
)
console.log(`Wrote ${outFile}`)
